import re

SYSTEM_PROMPT = """
你是专业的会议纪要助手，擅长将口语化会议转写整理为结构清晰、信息密度高的商务纪要。

工作原则：
1. 严格基于转写内容，禁止编造未出现的人名、机构、时间、数字、决策
2. 将口语整理为简洁、专业的书面表达，删除重复、语气词和无效寒暄
3. 按指定模板输出 Markdown，章节标题根据会议实际话题动态命名，不要用固定空泛标题
4. 每个要点应信息完整（谁、做了什么、关键判断/数据/结论），避免一句话敷衍
5. 信息不足时写「未提及」，不要猜测
6. 「AI洞察」写趋势、模式、隐含挑战等分析性观点，不要重复正文已列事实
7. 「待办」仅提取会议中明确提出的任务；无则写「本次会议未明确待办事项」
"""


def _has_speaker_labels(transcript: str) -> bool:
    return bool(re.search(r'\[说话人\d+\]|\[([^\]]+)\]|发言人\d+|说话人\d+[:：]', transcript))


def build_meeting_prompt(transcript: str, meeting_name: str | None = None) -> str:
    has_speakers = _has_speaker_labels(transcript)
    name_hint = (meeting_name or "").strip()
    name_line = f"\n【已知会议名称（可作主题参考）】{name_hint}" if name_hint else ""

    participant_hint = (
        "参与人：从转写中的说话人标签、自我介绍或称呼中提取，多人用顿号分隔；无法识别则写「未提及」。"
        if has_speakers
        else "参与人：从转写中出现的姓名或称呼推断；无法识别则写「未提及」。"
    )

    return f"""
请根据以下会议转写，生成结构化会议纪要。输出风格须接近「头部战略/品牌咨询类会议纪要」：先元信息 + 一段总述，再按话题分章深入展开，最后附 AI 洞察与待办。

【输出格式 — 严格按此结构，保留 Markdown 标题层级，不要输出格式说明或多余前后缀】

主题: （概括本次会议核心议题，10～25 字；可参考已知会议名称）
时间: （从转写推断或写「未提及」）
参与人: （{participant_hint.replace("参与人：", "")}）



（用 1 段话 120～200 字概括：会议背景、讨论主线、关键结论或共识；书面语、信息密度高，类似咨询纪要开篇总述）

## （第一大主题 — 根据内容自拟，如「公司背景与技术演进」「项目进展与风险」等）

### （子话题标题 — 自拟，简短有力）
- （要点：完整句，含关键事实/判断/数据；可多条）
- （要点）

### （子话题标题）
- （要点）

## （第二大主题）
### （子话题）
- （要点）

（按实际内容继续 3～6 个一级主题 `##`，每个主题下 1～4 个 `###` 子话题；章节名必须贴合本场会议，禁止机械套用「关键词」「章节速览」等空标题）

## AI洞察

- （从更高视角提炼 2～4 条：行业趋势、认知框架、传播/组织/战略层面的启示；须有分析深度，勿复述上文）
- （洞察）

## 待办

- （任务描述 + 负责人/对接人，未提及则省略负责人；每条一行，不用表格）
- （无明确待办则只写一行：本次会议未明确待办事项）

【写作要求】
- 一级主题 `##` 数量通常 3～6 个，长会可略多，短会可略少
- 子话题下的要点用 `-` 列表，每条 1～3 句，保留转写中的专有名词、数字、人名
- 不要输出「关键词」「全文概要」「章节速览」「要点回顾」等旧版听悟结构
- 不要输出代码块包裹全文
{name_line}

【转写内容】
{transcript}
"""
