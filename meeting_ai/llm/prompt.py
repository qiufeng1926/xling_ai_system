import re

SYSTEM_PROMPT = """
你是通义听悟风格的智能会议纪要助手，擅长从口语化会议转写中提取结构化信息。

工作原则：
1. 严格基于转写内容，禁止编造未出现的人名、时间、数字、决策
2. 将口语整理为简洁、专业的书面表达，删除重复、语气词和无效寒暄
3. 按「智能速览」结构输出 Markdown，层次清晰，便于快速阅读
4. 信息不足时如实写「未提及」，不要猜测
5. 章节速览按话题自然分段（通常 3～6 章，中粒度），标题简短有力
6. 待办事项仅提取明确提出的任务；无则写「本次会议未明确待办事项」
"""


def _has_speaker_labels(transcript: str) -> bool:
    return bool(re.search(r'\[说话人\d+\]|发言人\d+|说话人\d+[:：]', transcript))


def build_meeting_prompt(transcript: str) -> str:
    has_speakers = _has_speaker_labels(transcript)
    speaker_section = """
## 发言总结

> 按发言人归纳核心观点（每人 2～4 条要点，不重复、不遗漏关键立场）

### 说话人1
- 观点要点

### 说话人2
- 观点要点
""" if has_speakers else """
## 发言总结

> 转写中未区分发言人，本节根据讨论内容归纳主要观点（3～5 条）
- 要点1
- 要点2
"""

    return f"""
请根据以下会议转写，生成与「通义听悟 · 智能速览」风格一致的结构化纪要。

【输出格式要求】
严格按以下 Markdown 结构输出，保留所有二级标题，不要添加额外说明文字：

## 关键词

> 提炼 3～8 个核心关键词，用行内代码格式展示，例如：`项目进度` `资源协调`

## 全文概要

> 用 1 段话（80～150 字）概括会议背景、讨论焦点和整体结论

## 章节速览

> 按话题划分章节，每章包含：章节标题 + 2～4 条要点（书面化、信息密度高）

### 1. 章节标题
- 要点
- 要点

### 2. 章节标题
- 要点
- 要点
{speaker_section}
## 要点回顾

> 梳理会议中的关键信息、重要结论、争议点或需跟进的问题（5～8 条）

1. 要点
2. 要点

## 待办事项

> 表格列出明确任务；负责人或时间未提及则填「未提及」

| 序号 | 待办事项 | 负责人 | 时间 |
|------|----------|--------|------|
| 1 | 具体任务描述 | 未提及 | 未提及 |

---

【转写内容】
{transcript}
"""
